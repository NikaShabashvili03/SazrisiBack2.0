def main():
    created_count = 0
    existed_count = 0

    for topic in TOPICS:
        obj, created = ImitationTopic.objects.get_or_create(
            name=topic["name"],
            defaults={
                "url": "",
                "description": topic["description"],
            },
        )
        if created:
            created_count += 1
            print(f"  [+] {topic['name']}")
        else:
            existed_count += 1
            print(f"  [=] {topic['name']} (already exists)")

    print(f"\nDone. Created: {created_count}, Already existed: {existed_count}")


if __name__ == "__main__":
    main()
